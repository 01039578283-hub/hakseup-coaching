def choose(subject, source_text):
    pool = ENGLISH if subject == '영어' else MATH
    # Workbook evidence chooses the focus; no random or keyword-spinning seed.
    scores = [(sum(source_text.count(word) for word in p['words']), i, p) for i, p in enumerate(pool)]
    ranked = sorted(scores, key=lambda value: (-value[0], value[1]))
    return [value[2] for value in ranked[:2]], {p['key']:score for score, _, p in scores}
